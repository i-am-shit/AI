def is_variable(x):
    return x in ['x', 'y', 'z', 'X', 'Y', 'Z']


def unify(x, y, substitutions):

    if x == y:
        return substitutions

    if is_variable(x):
        return unify_variable(x, y, substitutions)

    if is_variable(y):
        return unify_variable(y, x, substitutions)

    return None


def unify_variable(variable, value, substitutions):

    if variable in substitutions:
        return unify(substitutions[variable], value, substitutions)

    if is_variable(value) and value in substitutions:
        return unify(variable, substitutions[value], substitutions)

    substitutions[variable] = value
    return substitutions


def parse_expression(expression):

    predicate = expression.split("(")[0]

    arguments = expression[
        expression.find("(") + 1:
        expression.find(")")
    ].split(",")

    arguments = [arg.strip() for arg in arguments]

    return predicate, arguments


def unify_expressions(exp1, exp2):

    predicate1, args1 = parse_expression(exp1)
    predicate2, args2 = parse_expression(exp2)

    print("\nExpression 1:", exp1)
    print("Expression 2:", exp2)

    if predicate1 != predicate2:
        print("\nFAILURE: Predicate symbols are different")
        return

    if len(args1) != len(args2):
        print("\nFAILURE: Number of arguments is different")
        return

    substitutions = {}

    for i in range(len(args1)):

        result = unify(args1[i], args2[i], substitutions)

        if result is None:
            print("\nUNIFICATION FAILED")
            return

    print("\nUNIFICATION SUCCESSFUL")
    print("Substitutions:")

    for variable, value in substitutions.items():
        print(variable, "=", value)


